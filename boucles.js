// Pseudo code boucle Tant que (for)
/*
i = 0
Tant que i est < 10
    ajouter 1 à i
    afficher i
Fin tant que
*/

// Javascript
// Boucle for (on connait le nombre d'itérations)
for (let i=0 ; i<7 ; i++ ) {
    console.log(i);
}

// Boucle while (on ne connait pas à l'avance le nombre d'itérations)
let i = 0;
while(i<7) {
    i = i + 1;
    console.log(i);
}